import assert from "node:assert/strict";
import { Runtime } from "../runtime/runtime.js";
import { ProjectSystem } from "../systems/project/system.js";
import { ArrangementSystem } from "../systems/arrangement/system.js";
import { TimelineSystem } from "../systems/timeline/system.js";
import { StudioSystem } from "../systems/studio/system.js";
const runtime = new Runtime();
const project = new ProjectSystem(runtime);
const arrangement = new ArrangementSystem(runtime);
const timeline = new TimelineSystem(runtime);
const studio = new StudioSystem(runtime);
assert.equal(project.invoke("create", "p1", "Demo").title, "Demo");
assert.throws(() => project.invoke("create", "p1", "Duplicate"));
assert.equal(arrangement.invoke("create", "a1", "p1").projectId, "p1");
assert.equal(arrangement.invoke("addClip", "a1", {trackId:"t1",startBeat:0,lengthBeats:8}).lengthBeats, 8);
assert.throws(() => arrangement.invoke("addClip", "a1", {trackId:"t1",startBeat:-1,lengthBeats:8}));
assert.equal(timeline.invoke("beatsToSeconds", 4, 120), 2);
assert.equal(timeline.invoke("secondsToBeats", 2, 120), 4);
assert.throws(() => timeline.invoke("beatsToSeconds", 4, 0));
assert.equal(studio.invoke("open", "s1", "p1").state, "open");
assert.equal(studio.invoke("close", "s1").state, "closed");
assert.throws(() => studio.invoke("close", "s1"));
assert.ok(runtime.registry.events.length >= 8);
console.log("Production system tests passed");
