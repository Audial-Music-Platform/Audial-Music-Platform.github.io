import assert from "node:assert/strict";
import { Runtime } from "../runtime/runtime.js";
import { EANSystem } from "../systems/ean/system.js";
import { QRSystem } from "../systems/qr/system.js";
Object.defineProperty(globalThis,"navigator",{configurable:true,value:{userAgent:"Mozilla/5.0 Firefox/150",maxTouchPoints:0}});
globalThis.window={innerWidth:1280,innerHeight:720,AudioContext:function(){}};
globalThis.location={href:"https://audial-music-platform.github.io/"};
const {BrowserSystem}=await import("../systems/browser/system.js");
const runtime=new Runtime();
const ean=new EANSystem(runtime), qr=new QRSystem(runtime), browser=new BrowserSystem(runtime);
assert.equal(ean.invoke("encode13","590123412345").value,"5901234123457");
assert.equal(ean.invoke("encode13","590123412345").bits.length,95);
assert.equal(ean.invoke("validate13","5901234123457"),true);
assert.equal(ean.invoke("validate13","5901234123458"),false);
assert.throws(()=>ean.invoke("encode13","5901234123458"));
assert.equal(qr.invoke("prepare","demo","audial://music/tracks/demo").status,"pending-encoder");
assert.throws(()=>qr.invoke("prepare","bad","x".repeat(1025)));
assert.equal(browser.invoke("detect").browser,"Firefox");
assert.equal(browser.invoke("open","/music"),"https://audial-music-platform.github.io/music");
assert.throws(()=>browser.invoke("open","javascript:alert(1)"));
console.log("Browser/EAN/QR tests passed");
